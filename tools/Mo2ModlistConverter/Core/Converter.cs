using System.Globalization;
using System.Text.Json;
using System.Text.Json.Nodes;
using DarkestDungeonSaveEditor.Core;

namespace DarkestDungeon.ModOrder;

public static class Converter
{
    private const string AppliedKey = "applied_ugcs_1_0";

    public static async Task<ConversionPlan> PreviewAsync(ConversionRequest request, CancellationToken token = default)
    {
        token.ThrowIfCancellationRequested();
        request = Normalize(request);
        if (!Path.GetFileName(request.SavePath).Equals("persist.game.json", StringComparison.OrdinalIgnoreCase))
            throw new InvalidDataException("Select persist.game.json from the save profile, not another persist file.");
        var reader = new InputReader();
        var saveBytes = reader.Read(request.SavePath, required: true)!;
        var modlistBytes = reader.Read(request.ModlistPath, required: true)!;
        var entries = ModCatalog.ReadModlist(modlistBytes);
        var installed = ModCatalog.ReadInstalled(request.ModsDirectory, reader);
        token.ThrowIfCancellationRequested();
        using var temporary = new TemporaryDirectory();
        var original = Path.Combine(temporary.Path, "persist.game.json");
        var decoded = Path.Combine(temporary.Path, "decoded.json");
        await File.WriteAllBytesAsync(original, saveBytes, token).ConfigureAwait(false);
        await DsonSaveCodec.CreateNative().DecodeAsync(original, decoded, token).ConfigureAwait(false);
        var document = InputReader.Json(await File.ReadAllTextAsync(decoded, token).ConfigureAwait(false));
        var root = document["base_root"] as JsonObject
            ?? throw new InvalidDataException("persist.game.json has no base_root object.");
        var applied = ReadApplied(root);
        var rows = new List<PreviewRow>();
        var errors = new List<string>();
        string? outputModlist = null;
        string? outputJson = null;
        if (request.Direction == ConversionDirection.SaveToMo2)
        {
            var selected = new List<ModlistEntry>();
            var selectedFolders = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
            foreach (var item in applied)
            {
                var matches = installed.Where(mod => mod.Candidates.Any(id => id.Key == item.Id.Key)).ToArray();
                var problem = item.Id.IsMerge
                    ? "A save containing merge mod cannot recover its original MO2 list. Use a native save from before the MO2 migration."
                    : matches.Length == 0 ? $"No MO2 folder matches {item.Id}. Sync/install that Mod in the selected MO2 instance."
                    : matches.Length > 1 ? $"Multiple MO2 folders match {item.Id}: {string.Join(", ", matches.Select(m => m.Folder))}."
                    : !selectedFolders.Add(matches[0].Folder) ? $"MO2 folder '{matches[0].Folder}' maps to more than one enabled native Mod." : "";
                if (problem.Length > 0) errors.Add(problem);
                var folder = matches.Length == 1 ? matches[0].Folder : "";
                rows.Add(new(rows.Count + 1, true, folder, item.Id.Source, item.Id.Name,
                    folder.Length > 0 ? Path.Combine(request.ModsDirectory, folder) : "", problem));
                if (problem.Length == 0) selected.Add(new(folder, '+'));
            }
            var remainder = entries.Where(e => !e.IsSeparator && !selectedFolders.Contains(e.Folder))
                .Select(e => new ModlistEntry(e.Folder, '-')).ToList();
            var listed = entries.Select(e => e.Folder).Concat(selectedFolders).ToHashSet(StringComparer.OrdinalIgnoreCase);
            remainder.AddRange(installed.Where(m => !listed.Contains(m.Folder)).Select(m => new ModlistEntry(m.Folder, '-')));
            foreach (var entry in remainder)
            {
                var mod = installed.SingleOrDefault(m => m.Folder.Equals(entry.Folder, StringComparison.OrdinalIgnoreCase));
                var id = mod?.Candidates.Count == 1 ? mod.Candidates[0] : null;
                rows.Add(new(null, false, entry.Folder, id?.Source ?? "", id?.Name ?? "", "",
                    mod?.Error ?? (mod is null ? "Folder is missing; retained as disabled." : "")));
            }
            // Keep separator lines at their previous file positions; only regular Mod
            // slots are reordered. Disabled Mods retain their relative text order.
            var queue = new Queue<ModlistEntry>(selected.Concat(remainder));
            var output = new List<ModlistEntry>();
            foreach (var entry in entries)
            {
                if (entry.IsSeparator) output.Add(entry);
                else if (queue.TryDequeue(out var next)) output.Add(next);
            }
            output.AddRange(queue);
            outputModlist = "# This file was generated by Darkest Dungeon Mod Order Converter.\r\n" +
                string.Concat(output.Select(e => $"{e.State}{e.Folder}\r\n"));
        }
        else
        {
            var selectedIds = new HashSet<string>(StringComparer.Ordinal);
            var newApplied = new JsonObject();
            var order = 0;
            foreach (var entry in entries.Where(e => !e.IsSeparator))
            {
                var mod = installed.SingleOrDefault(m => m.Folder.Equals(entry.Folder, StringComparison.OrdinalIgnoreCase));
                if (!entry.Enabled)
                {
                    rows.Add(new(null, false, entry.Folder, "", "", "", ""));
                    continue;
                }
                order++;
                var candidates = mod?.Candidates ?? [];
                var problem = mod is null ? $"Enabled MO2 folder is missing: {entry.Folder}."
                    : mod.Error is not null ? $"{entry.Folder}: {mod.Error}"
                    : candidates.Count != 1 ? $"{entry.Folder}: ambiguous native source ({string.Join(" or ", candidates)}). Resync its origin metadata with the Darkest Dungeon sync tool."
                    : candidates[0].IsMerge ? $"{entry.Folder}: merge mod is a generated MO2 container, not an individual native Mod."
                    : !selectedIds.Add(candidates[0].Key) ? $"{entry.Folder}: duplicate native identity {candidates[0]}." : "";
                var id = candidates.Count == 1 ? candidates[0] : null;
                rows.Add(new(order, true, entry.Folder, id?.Source ?? "", id?.Name ?? "",
                    mod is not null ? Path.Combine(request.ModsDirectory, mod.Folder) : "", problem));
                if (problem.Length > 0) { errors.Add(problem); continue; }
                var value = applied.FirstOrDefault(item => item.Id.Key == id!.Key).Value?.DeepClone() as JsonObject ?? new JsonObject();
                value["name"] = id!.Name;
                value["source"] = id.Source;
                newApplied[(order - 1).ToString(CultureInfo.InvariantCulture)] = value;
            }
            root[AppliedKey] = newApplied;
            outputJson = document.ToJsonString(InputReader.JsonOptions);
        }
        token.ThrowIfCancellationRequested();
        return new(request, rows, errors, reader.Fingerprint(request), saveBytes, modlistBytes, outputModlist, outputJson);
    }

    // Always export a new directory. The supplied source files are never write targets.
    public static async Task<string> ExportAsync(ConversionPlan preview, string newDirectory, CancellationToken token = default)
    {
        if (!preview.CanExport) throw new InvalidOperationException("Resolve the preview errors before exporting.");
        var current = await PreviewAsync(preview.Request, token).ConfigureAwait(false);
        if (!current.CanExport || current.Fingerprint != preview.Fingerprint)
            throw new InvalidOperationException("Inputs changed after preview. Preview again before exporting.");
        newDirectory = Path.GetFullPath(newDirectory);
        if (Path.Exists(newDirectory)) throw new IOException($"Export destination already exists: {newDirectory}");
        var parent = Path.GetDirectoryName(newDirectory);
        if (parent is null || !Directory.Exists(parent)) throw new DirectoryNotFoundException("Select an existing parent directory for the export.");
        var staging = Path.Combine(parent, ".mod-order-" + Guid.NewGuid().ToString("N") + ".tmp");
        Directory.CreateDirectory(staging);
        try
        {
            var backup = Directory.CreateDirectory(Path.Combine(staging, "original")).FullName;
            if (current.Request.Direction == ConversionDirection.SaveToMo2)
            {
                await File.WriteAllBytesAsync(Path.Combine(backup, "modlist.txt"), current.ModlistBytes, token).ConfigureAwait(false);
                await File.WriteAllTextAsync(Path.Combine(staging, "modlist.txt"), current.OutputModlist, InputReader.Utf8, token).ConfigureAwait(false);
            }
            else
            {
                var original = Path.Combine(backup, "persist.game.json");
                await File.WriteAllBytesAsync(original, current.SaveBytes, token).ConfigureAwait(false);
                using var temporary = new TemporaryDirectory();
                var json = Path.Combine(temporary.Path, "edited.json");
                var verified = Path.Combine(temporary.Path, "verified.json");
                var output = Path.Combine(staging, "persist.game.json");
                await File.WriteAllTextAsync(json, current.OutputJson, InputReader.Utf8, token).ConfigureAwait(false);
                var codec = DsonSaveCodec.CreateNative();
                await codec.EncodeAsync(json, output, original, token).ConfigureAwait(false);
                await codec.DecodeAsync(output, verified, token).ConfigureAwait(false);
                var roundTrip = InputReader.Json(await File.ReadAllTextAsync(verified, token).ConfigureAwait(false));
                if (!JsonNode.DeepEquals(InputReader.Json(current.OutputJson!), roundTrip))
                    throw new InvalidDataException("Save round-trip verification failed. No export was published.");
            }
            await File.WriteAllTextAsync(Path.Combine(staging, "conversion-report.json"), JsonSerializer.Serialize(new
            {
                direction = current.Request.Direction.ToString(), current.Request, current.Fingerprint,
                current.EnabledCount, current.Rows,
                note = "Priority is highest first. Only enabled membership and order are transferred; MO2 merged content is not converted."
            }, InputReader.JsonOptions), InputReader.Utf8, token).ConfigureAwait(false);
            await File.WriteAllTextAsync(Path.Combine(staging, "HOW-TO-APPLY.txt"), current.Request.Direction == ConversionDirection.SaveToMo2
                ? "Close MO2 and the game. Back up your target profile's modlist.txt, then replace it with this export. Reopen that MO2 profile. The original list is also saved in original/modlist.txt. Only enabled membership and priority are inherited; separator headings may describe different groups after reordering.\r\n"
                : "Close the game and MO2. Back up the entire target save profile before replacing ONLY persist.game.json with this export. Launch the game directly, without MO2. The original file is in original/persist.game.json. DLC and progress are unchanged. This conversion assumes MO2 and native Mods are synchronized. It transfers membership and priority, not merged resource files.\r\n",
                InputReader.Utf8, token).ConfigureAwait(false);
            token.ThrowIfCancellationRequested();
            Directory.Move(staging, newDirectory); // Refuses existing destinations; no overwrite.
            return newDirectory;
        }
        finally
        {
            // Only this call's private staging directory can be removed.
            if (Directory.Exists(staging)) Directory.Delete(staging, recursive: true);
        }
    }

    private static ConversionRequest Normalize(ConversionRequest request)
    {
        if (!Enum.IsDefined(request.Direction)) throw new ArgumentOutOfRangeException(nameof(request.Direction));
        static string Required(string value, string label) => !string.IsNullOrWhiteSpace(value)
            ? Path.GetFullPath(value.Trim()) : throw new ArgumentException($"Select {label}.");
        return request with
        {
            SavePath = Required(request.SavePath, "persist.game.json"),
            ModlistPath = Required(request.ModlistPath, "the MO2 profile's modlist.txt"),
            ModsDirectory = Required(request.ModsDirectory, "the MO2 mods directory")
        };
    }

    private static List<(NativeId Id, JsonObject Value)> ReadApplied(JsonObject root)
    {
        if (!root.TryGetPropertyValue(AppliedKey, out var node)) return [];
        if (node is not JsonObject applied) throw new InvalidDataException($"{AppliedKey} must be an object.");
        var items = new SortedDictionary<int, (NativeId Id, JsonObject Value)>();
        var ids = new HashSet<string>(StringComparer.Ordinal);
        foreach (var pair in applied)
        {
            if (!int.TryParse(pair.Key, NumberStyles.None, CultureInfo.InvariantCulture, out var order) || pair.Value is not JsonObject entry)
                throw new InvalidDataException($"Malformed enabled Mod entry: {pair.Key}");
            if (entry["name"] is not JsonValue nameValue || !nameValue.TryGetValue<string>(out var name) || string.IsNullOrWhiteSpace(name) ||
                entry["source"] is not JsonValue sourceValue || !sourceValue.TryGetValue<string>(out var source))
                throw new InvalidDataException($"Incomplete enabled Mod entry: {pair.Key}");
            source = source.Equals("Steam", StringComparison.OrdinalIgnoreCase) ? "Steam"
                : source.Equals("mod_local_source", StringComparison.OrdinalIgnoreCase) ? "mod_local_source"
                : throw new InvalidDataException($"Unknown native Mod source '{source}' in entry {pair.Key}.");
            if (source == "Steam" && !ModCatalog.ValidWorkshopId(name)) throw new InvalidDataException($"Invalid Workshop id: {name}");
            var id = new NativeId(source, name);
            if (!ids.Add(id.Key) || !items.TryAdd(order, (id, entry)))
                throw new InvalidDataException($"Duplicate Mod identity or numeric order: {pair.Key}, {id}");
        }
        return items.Values.ToList();
    }
}
